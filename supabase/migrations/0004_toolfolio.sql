-- Toolfolio-style extras. All optional: anything left empty hides the UI that uses it.
alter table bookmarks
  add column tagline text not null default '',          -- 2–3 word label on cards, e.g. "Screen Capture Workspace"
  add column subscriber boolean not null default false, -- gold tick (white otherwise) + "Subscriber spotlight"
  add column deal text not null default '',             -- e.g. "25% off": card hover + "Top deals"
  add column deal_code text not null default '',        -- copied when the deal is clicked
  add column startup_position int,                      -- set = "Featured startups", in this order
  add column trending_position int;                     -- set = "Trending", in this order

alter table posts add column featured_position int;     -- set = "Featured articles" (else the newest three)

-- Saved collections and articles (bookmarks stay in `saves`).
create table list_saves (
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  kind text not null check (kind in ('collection', 'post')),
  slug text not null,
  created_at timestamptz not null default now(),
  primary key (user_id, kind, slug)
);
alter table list_saves enable row level security;
create policy "own list saves: read" on list_saves for select to authenticated using (auth.uid() = user_id);
create policy "own list saves: add" on list_saves for insert to authenticated with check (auth.uid() = user_id);
create policy "own list saves: remove" on list_saves for delete to authenticated using (auth.uid() = user_id);

